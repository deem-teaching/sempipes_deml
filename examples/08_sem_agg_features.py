"""sem_agg_features: let an LLM write join-and-aggregate code for a one-to-many relationship.

What the operator does
    ``left.sem_agg_features(right, left_on, right_on, nl_prompt, name, how_many)`` handles tables where every row of
    ``left`` (here: a shopping basket) has many matching rows in ``right`` (the products in the basket). The LLM sees
    summaries of both tables and writes a function that groups ``right``, computes ``how_many`` aggregate features
    and left-joins them onto ``left``. As with all code-generating operators, the code is written once at fit time.

What this example shows
    Credit-card fraud detection on skrub's ``credit_fraud`` data. We use 3000 baskets: fraud is rare (about 1 %), so
    we keep 500 fraudulent and 2500 legitimate ones. A hand-written baseline (number of products and summed price
    per basket) is compared with LLM-generated aggregations, both measured by ROC AUC on a held-out test set.

How to run (from the repository root)
    poetry run python examples/08_sem_agg_features.py

Runtime / cost
    About 1-2 minutes, with 1 LLM call (plus retries if the generated code fails validation).
"""

import pandas as pd
import skrub
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import train_test_split

import sempipes  # importing sempipes adds the .sem_* methods to skrub DataOps

SEED = 0


def simple_aggregates(baskets: pd.DataFrame, products: pd.DataFrame) -> pd.DataFrame:
    """Hand-written baseline: number of products and summed price per basket."""
    stats = products.groupby("basket_ID").agg(n_products=("item", "size"), sum_cash_price=("cash_price", "sum"))
    return baskets.merge(stats, left_on="ID", right_index=True, how="left")


def build_pipeline(use_llm: bool) -> skrub.DataOp:
    baskets = sempipes.as_X(skrub.var("baskets"), "Online shopping baskets, one row per basket")
    labels = sempipes.as_y(skrub.var("labels"), "1 if the basket is fraudulent, 0 otherwise")
    products = skrub.var("products")

    if use_llm:
        features = baskets.sem_agg_features(
            products,
            left_on="ID",
            right_on="basket_ID",
            nl_prompt="Generate product features that distinguish fraudulent baskets from regular ones, e.g. "
            "statistics of prices, quantities and product categories, or combinations of them.",
            name="basket_features",
            how_many=8,
        )
    else:
        features = skrub.deferred(simple_aggregates)(baskets, products)  # run a plain function inside the pipeline

    features = features.drop(columns=["ID"])  # the basket ID itself is not a meaningful feature
    encoded = features.skb.apply(skrub.TableVectorizer())
    return encoded.skb.apply(HistGradientBoostingClassifier(random_state=SEED), y=labels)


def main() -> None:
    dataset = skrub.datasets.fetch_credit_fraud()
    baskets = dataset.baskets
    fraud = baskets[baskets["fraud_flag"] == 1].sample(n=500, random_state=SEED)
    legit = baskets[baskets["fraud_flag"] == 0].sample(n=2500, random_state=SEED)
    baskets = pd.concat([fraud, legit])
    products = dataset.products[dataset.products["basket_ID"].isin(baskets["ID"])]
    train, test = train_test_split(baskets, test_size=0.3, stratify=baskets["fraud_flag"], random_state=SEED)
    print(f"{len(train)} training and {len(test)} test baskets, {len(products)} products")

    for use_llm in (False, True):
        pipeline = build_pipeline(use_llm)
        env = pipeline.skb.get_data()  # default values of SemPipes' hidden helper variables
        learner = pipeline.skb.make_learner()
        learner.fit({**env, "baskets": train[["ID"]], "labels": train["fraud_flag"], "products": products})
        fraud_probability = learner.predict_proba({**env, "baskets": test[["ID"]], "products": products})[:, 1]

        title = "LLM-generated aggregations" if use_llm else "Baseline: hand-written aggregations"
        print(f"\n=== {title} ===\nTest ROC AUC: {roc_auc_score(test['fraud_flag'], fraud_probability):.3f}")

    print("\n=== Code generated by the LLM ===")
    print(learner.find_fitted_estimator("basket_features").generated_code_)


if __name__ == "__main__":
    main()
