"""sem_gen_features: let an LLM write feature-engineering code (CAAFE-style).

What the operator does
    ``DataOp.sem_gen_features(nl_prompt, name, how_many)`` shows the LLM the column names, dtypes and a few sample
    rows of a table. It then asks for a pandas function that adds up to ``how_many`` new feature columns based on
    world knowledge, e.g. "total living area = basement + 1st floor + 2nd floor". The code is generated and
    validated once, when the pipeline is fitted. Later it is re-applied to new data without further LLM calls.

What this example shows
    Kaggle's house-prices data (462 houses, 79 attributes). We put the official column documentation into the
    prompt, let the LLM generate features and compare the same gradient-boosting model with and without them on a
    hold-out set (RMSE on the log sale price, as in the Kaggle competition, and R²). We also print the generated code.

How to run (from the repository root)
    poetry run python examples/07_sem_gen_features.py

Runtime / cost
    About 1-2 minutes, with 1 LLM call (plus retries if the generated code fails validation). The prompt includes
    the 13 KB column documentation, so the call has about 6k input tokens.
"""

from pathlib import Path

import numpy as np
import pandas as pd
import skrub
from sklearn.ensemble import HistGradientBoostingRegressor
from sklearn.metrics import mean_squared_error, r2_score
from sklearn.model_selection import train_test_split

import sempipes  # importing sempipes adds the .sem_* methods to skrub DataOps

DATA_DIR = Path(__file__).parent / "data"


def build_pipeline(column_documentation: str | None) -> skrub.DataOp:
    houses = skrub.var("houses").skb.mark_as_X()
    log_price = skrub.var("log_price").skb.mark_as_y()

    if column_documentation is not None:
        houses = houses.sem_gen_features(
            nl_prompt=(
                "Generate features that help to predict the sale price of a house, for example the total living "
                "area, the total number of bathrooms, the age of the house when it was sold, or interactions of "
                "quality and size. Avoid divisions by zero. Here is the documentation of all columns:\n"
                + column_documentation
            ),
            name="house_features",
            how_many=8,
        )

    encoded = houses.skb.apply(skrub.TableVectorizer())
    return encoded.skb.apply(HistGradientBoostingRegressor(random_state=0), y=log_price)


def main() -> None:
    data = pd.read_csv(DATA_DIR / "house_prices" / "house_prices.csv")
    documentation = (DATA_DIR / "house_prices" / "data_description.txt").read_text(encoding="utf-8")
    X = data.drop(columns=["Id", "SalePrice"])
    y = np.log1p(data["SalePrice"])  # Kaggle scores this competition with the RMSE of the log price
    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=42)

    for title, docs in [("Baseline (original columns)", None), ("With LLM-generated features", documentation)]:
        pipeline = build_pipeline(docs)
        # get_data() returns default values for SemPipes' hidden helper variables. We add our data to them.
        env = pipeline.skb.get_data()
        learner = pipeline.skb.make_learner()
        learner.fit({**env, "houses": X_train, "log_price": y_train})  # the LLM writes the feature code here
        predictions = learner.predict({**env, "houses": X_test})  # reuses the stored code: no LLM call

        rmse = np.sqrt(mean_squared_error(y_test, predictions))
        print(f"=== {title} ===\nRMSE (log price): {rmse:.4f}   R²: {r2_score(y_test, predictions):.3f}\n")

    # The fitted operator keeps the generated code, so you can read (and reuse) it.
    generator = learner.find_fitted_estimator("house_features")
    print("=== Code generated by the LLM ===")
    print(generator.generated_code_)


if __name__ == "__main__":
    main()
