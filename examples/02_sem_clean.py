"""sem_clean: clean messy columns with LLM-generated pandas code.

What the operator does
    ``DataOp.sem_clean(nl_prompt, columns)`` shows the LLM a preview and summary statistics of the chosen columns and
    asks it to write a function ``clean_columns(df, columns)``. SemPipes tests the code on a sample and asks the LLM
    for a fix if it fails. The working code is stored when the pipeline is fitted. Applying it to data needs no
    further LLM calls.

What this example shows
    A small hand-made table with typical data-entry problems: stray whitespace, inconsistent capitalisation,
    numbers stored as text, placeholder strings for missing values and an impossible age. We print the table and
    its dtypes before and after cleaning, plus the code that the LLM wrote.

How to run (from the repository root)
    poetry run python examples/02_sem_clean.py

Runtime / cost
    Under a minute, with 1 LLM call (plus up to 4 retries if the generated code fails).
"""

import pandas as pd
import skrub

import sempipes  # importing sempipes adds the .sem_* methods to skrub DataOps

DIRTY_PEOPLE = pd.DataFrame(
    {
        "name": [" Alice ", "bob", None, "CHARLIE  ", "martina", "Dave"],
        "age": ["25", "30 ", "NA", "forty", "150", "41"],
        "income": ["52,000", "61000", "$58,500", "n/a", "70k", "48000.50"],
    }
)

CLEANING_PROMPT = (
    "Strip whitespace from names and write them in title case. "
    "Convert age to an integer; values that are not numbers or lie outside 0-110 years become missing. "
    "Convert income to a float in US dollars ('70k' means 70000). "
    "Represent every missing value as a real missing value (NaN/None), never as a string such as 'NA' or 'n/a'."
)


def main() -> None:
    print("=== Before cleaning ===")
    print(DIRTY_PEOPLE.to_string())
    print(DIRTY_PEOPLE.dtypes.to_string())

    people = skrub.var("people")
    cleaned = people.sem_clean(nl_prompt=CLEANING_PROMPT, columns=["name", "age", "income"]).skb.set_name("cleaning")

    # Fitting the learner generates the cleaning code (LLM call); fit_transform also applies it to the data.
    learner = cleaned.skb.make_learner()
    result = learner.fit_transform({"people": DIRTY_PEOPLE})

    print("\n=== After cleaning ===")
    print(result.to_string())
    print(result.dtypes.to_string())

    # skrub wraps DataFrame transformers in an ApplyToFrame step. The SemPipes estimator is in `.transformer_`.
    cleaner = learner.find_fitted_estimator("cleaning").transformer_
    print("\n=== Code generated by the LLM ===")
    print("\n".join(cleaner.generated_code_))

    # The learner can now clean new rows with the stored code, without calling the LLM again.
    new_rows = pd.DataFrame({"name": ["  eve", "FRANK"], "age": ["n/a", " 33"], "income": ["39k", "$45,000"]})
    print("\n=== Cleaning new data with the fitted learner ===")
    try:
        print(learner.transform({"people": new_rows}).to_string())
    except Exception as error:  # pylint: disable=broad-exception-caught
        # The generated code was only validated on the data it was generated from. New data with other quirks
        # (e.g. a column that is entirely missing) can still break it - always test generated code on fresh data.
        print(f"The generated code fails on the new rows: {type(error).__name__}: {error}")


if __name__ == "__main__":
    main()
